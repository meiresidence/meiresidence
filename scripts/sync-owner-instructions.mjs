// Nightly mirror of the owner's standing instructions into the repo.
//
// The live copy lives in the CRM as notes, so a rule Eglent sends on WhatsApp is
// in front of the next client within a minute. This job writes the active rules
// into knowledge/owner-instructions.md so they are also versioned, reviewable in
// a diff, and loadable at boot when the CRM read fails.
//
// It NEVER writes to the CRM. Notes are the source of truth; this is a mirror.
//
//   node scripts/sync-owner-instructions.mjs           # write the file
//   node scripts/sync-owner-instructions.mjs --check   # exit 1 if it would change
//
// Exit codes: 0 wrote or already current, 1 --check found drift, 2 error.

import fs from 'fs';
import path from 'path';
import { createInstructionStore, formatRule, instructionsContactId } from '../src/instructions.js';

const OUT = path.resolve('knowledge/owner-instructions.md');
const CHECK = process.argv.includes('--check');

const apiKey = process.env.GHL_API_KEY;
const base = process.env.GHL_API_BASE || 'https://services.leadconnectorhq.com';
if (!apiKey) {
  console.error('[sync] GHL_API_KEY is required.');
  process.exit(2);
}

async function ghl(p, method = 'GET', body = null, version = '2021-04-15') {
  const res = await fetch(`${base}${p}`, {
    method,
    headers: {
      Authorization: `Bearer ${apiKey}`,
      Version: version,
      'Content-Type': 'application/json',
      Accept: 'application/json',
    },
    body: body ? JSON.stringify(body) : undefined,
  });
  const data = await res.json().catch(() => ({}));
  if (!res.ok) console.error('[sync][ghl]', method, p, res.status, JSON.stringify(data).slice(0, 200));
  return { ok: res.ok, data };
}

function render(rules) {
  const active = rules.filter((r) => r.status === 'active').sort((a, b) => a.n - b.n);
  const revoked = rules.filter((r) => r.status !== 'active').sort((a, b) => a.n - b.n);
  const header = [
    '# Owner standing instructions',
    '',
    '_Generated by `scripts/sync-owner-instructions.mjs`. **Do not edit by hand** — the',
    'live copy is the set of `[MEI-AGENT-RULE]` notes on CRM contact',
    `\`${instructionsContactId()}\`, and the next run overwrites whatever is here.`,
    'To change a rule, message the agent from an owner number; to remove one, tell it',
    'to drop that number._',
    '',
    'The agent reads the live notes on every client message. This file is the',
    'fallback it boots with when the CRM cannot be reached.',
    '',
    `Last synced: ${new Date().toISOString()} · ${active.length} active, ${revoked.length} revoked.`,
    '',
    '## Active',
    '',
  ];
  const body = active.length
    ? active.map((r) => formatRule(r)).join('\n\n')
    : '_None yet._';
  const tail = revoked.length
    ? ['', '## Revoked — kept so an old behaviour is still explainable', '', revoked.map((r) => formatRule(r)).join('\n\n')]
    : [];
  return [...header, body, ...tail, ''].join('\n');
}

(async () => {
  try {
    const store = createInstructionStore({ ghl });
    const rules = await store.load({ force: true });
    const next = render(rules);
    const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';

    // Only the "Last synced" line changing is not a change worth a commit.
    const strip = (t) => t.replace(/^Last synced:.*$/m, '');
    if (strip(prev) === strip(next)) {
      console.log(`[sync] no change — ${rules.filter((r) => r.status === 'active').length} active rule(s).`);
      process.exit(0);
    }
    if (CHECK) {
      console.error('[sync] knowledge/owner-instructions.md is out of date.');
      process.exit(1);
    }
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, next);
    console.log(`[sync] wrote ${OUT} — ${rules.filter((r) => r.status === 'active').length} active rule(s).`);
    process.exit(0);
  } catch (e) {
    console.error('[sync] failed:', e?.message || e);
    process.exit(2);
  }
})();
